CREATE TABLE IF NOT EXISTS public.ml_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','doctor','nurse','staff')),
  active SMALLINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  deleted_at TEXT
);

CREATE TABLE IF NOT EXISTS public.ml_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.ml_users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.ml_availability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES public.ml_users(id),
  date TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  location TEXT NOT NULL DEFAULT '',
  rate_cents INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS public.ml_reliever_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_by BIGINT NOT NULL REFERENCES public.ml_users(id),
  date TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  location TEXT NOT NULL,
  rate_cents INTEGER NOT NULL,
  required_questions TEXT NOT NULL DEFAULT '[]',
  required_uploads TEXT NOT NULL DEFAULT '[]',
  active SMALLINT NOT NULL DEFAULT 1,
  legacy_availability_id BIGINT UNIQUE,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS public.ml_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES public.ml_users(id),
  requester_id BIGINT NOT NULL REFERENCES public.ml_users(id),
  date TEXT NOT NULL,
  end_date TEXT NOT NULL DEFAULT '',
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  rate_cents INTEGER NOT NULL DEFAULT 0,
  location TEXT NOT NULL DEFAULT '',
  approval_owner TEXT NOT NULL DEFAULT 'admin' CHECK (approval_owner IN ('admin','assignee')),
  reliever_post_id BIGINT REFERENCES public.ml_reliever_posts(id),
  reliever_answers TEXT NOT NULL DEFAULT '[]',
  reliever_uploads TEXT NOT NULL DEFAULT '[]',
  status TEXT NOT NULL CHECK (status IN ('pending','approved','declined','cancelled')),
  notification_state TEXT NOT NULL DEFAULT 'not_configured',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  decided_at TEXT
);

CREATE TABLE IF NOT EXISTS public.ml_attendance (
  booking_id BIGINT PRIMARY KEY REFERENCES public.ml_bookings(id) ON DELETE CASCADE,
  clock_in_at TEXT NOT NULL,
  clock_out_at TEXT,
  clock_in_photo TEXT NOT NULL,
  clock_in_mime TEXT NOT NULL,
  clock_out_photo TEXT,
  clock_out_mime TEXT,
  document_file TEXT,
  document_name TEXT,
  document_mime TEXT,
  entry_source TEXT NOT NULL DEFAULT 'clock',
  evidence_note TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS public.ml_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.ml_login_attempts (
  attempt_key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  until_ms BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS ml_availability_date ON public.ml_availability(doctor_id,date);
CREATE INDEX IF NOT EXISTS ml_bookings_date ON public.ml_bookings(doctor_id,date,status);
CREATE INDEX IF NOT EXISTS ml_bookings_requester ON public.ml_bookings(requester_id,date,status);
CREATE INDEX IF NOT EXISTS ml_bookings_end_date ON public.ml_bookings(end_date,status);
CREATE INDEX IF NOT EXISTS ml_reliever_posts_date ON public.ml_reliever_posts(date,active);
CREATE UNIQUE INDEX IF NOT EXISTS ml_bookings_reliever_post ON public.ml_bookings(reliever_post_id) WHERE reliever_post_id IS NOT NULL;

-- Only the Edge Function's server-side secret can invoke this query bridge.
CREATE OR REPLACE FUNCTION public.moonlight_query(query_text TEXT, query_args JSONB DEFAULT '[]'::jsonb)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
  statement TEXT := query_text;
  value JSONB;
  replacement TEXT;
  marker_pos INTEGER;
  arg_index INTEGER;
  row_values JSONB := '[]'::jsonb;
  changed INTEGER := 0;
  inserted_id JSONB := NULL;
BEGIN
  IF statement IS NULL OR statement ~ ';' OR statement !~* '^\s*(SELECT|WITH|INSERT|UPDATE|DELETE)\M' THEN
    RAISE EXCEPTION 'Unsupported database query';
  END IF;
  IF jsonb_typeof(query_args) <> 'array' THEN RAISE EXCEPTION 'Query arguments must be an array'; END IF;

  IF jsonb_array_length(query_args) > 0 THEN
  FOR arg_index IN 0..jsonb_array_length(query_args)-1 LOOP
    marker_pos := strpos(statement, '?');
    IF marker_pos = 0 THEN RAISE EXCEPTION 'Query argument count does not match'; END IF;
    value := query_args->arg_index;
    replacement := CASE jsonb_typeof(value)
      WHEN 'null' THEN 'NULL'
      WHEN 'string' THEN quote_literal(value #>> '{}')
      WHEN 'number' THEN value::text
      WHEN 'boolean' THEN upper(value::text)
      ELSE quote_literal(value::text)
    END;
    statement := overlay(statement PLACING replacement FROM marker_pos FOR 1);
  END LOOP;
  END IF;
  IF strpos(statement, '?') > 0 THEN RAISE EXCEPTION 'Query argument count does not match'; END IF;

  IF statement ~* '^\s*(SELECT|WITH)\M' THEN
    EXECUTE 'SELECT COALESCE(jsonb_agg(to_jsonb(q)), ''[]''::jsonb) FROM (' || statement || ') AS q' INTO row_values;
  ELSE
    EXECUTE 'WITH q AS (' || statement || ' RETURNING *) SELECT COALESCE(jsonb_agg(to_jsonb(q)), ''[]''::jsonb) FROM q' INTO row_values;
    changed := jsonb_array_length(row_values);
    IF statement ~* '^\s*INSERT\M' AND changed > 0 THEN inserted_id := row_values->0->'id'; END IF;
  END IF;

  RETURN jsonb_build_object('rows',row_values,'changes',changed,'last_row_id',inserted_id);
END;
$function$;

REVOKE ALL ON FUNCTION public.moonlight_query(TEXT, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.moonlight_query(TEXT, JSONB) TO service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;

